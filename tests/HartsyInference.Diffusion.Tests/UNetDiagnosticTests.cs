    /// <summary>
    /// Runs a single UNet forward pass using reflection to access internal blocks,
    /// logging tensor stats at every intermediate point. This mirrors the Python
    /// dump_layer_outputs.py script for direct comparison.
    /// </summary>
    [Fact]
    public unsafe void InstrumentedUNetForwardPass()
    {
        if (!Directory.Exists(ModelDir))
        {
            _output.WriteLine($"SKIPPED: Model directory not found: {ModelDir}");
            return;
        }

        // Load UNet
        _output.WriteLine("Loading UNet...");
        UNet unet = new(UNetConfig.Sd15);
        using SafeTensorsLoader unetLoader = new();
        unetLoader.Load(Path.Combine(ModelDir, "unet", "diffusion_pytorch_model.fp16.safetensors"));
        unet.LoadWeights(CastWeightsToF32(unetLoader.GetAllTensors()));

        // Load text encoder for embeddings
        ClipTextEncoderConfig clipConfig = ClipTextEncoderConfig.Sd15;
        ClipTextEncoder textEncoder = new(clipConfig);
        using SafeTensorsLoader teLoader = new();
        teLoader.Load(Path.Combine(ModelDir, "text_encoder", "model.fp16.safetensors"));
        textEncoder.LoadWeights(CastWeightsToF32(teLoader.GetAllTensors()), "text_model");

        using CpuBackend backend = new();

        // Encode negative prompt (unconditional) for a single-pass test
        using HartsyInference.Tokenizers.ClipTokenizer tokenizer = new(
            Path.Combine(ModelDir, "tokenizer", "vocab.json"),
            Path.Combine(ModelDir, "tokenizer", "merges.txt"));
        int[] negativeTokens = tokenizer.Encode("blurry, bad quality");
        Tensor textEmb = textEncoder.Encode(backend, [negativeTokens]);

        // Create step 0 input: noise * InitialNoiseSigma * ScaleModelInput(0) = noise
        EulerDiscreteScheduler scheduler = new();
        scheduler.SetTimesteps(20);
        TensorShape latentShape = new(1, 4, 32, 32);
        Tensor noise = Diffusion.Utilities.SeedGenerator.CreateNoise(latentShape, 42);

        float initSigma = scheduler.InitialNoiseSigma;
        Tensor scaledNoise = new(latentShape, DType.F32);
        backend.Scale(scaledNoise, noise, initSigma);
        noise.Dispose();

        float inputScale = scheduler.ScaleModelInput(0);
        Tensor modelInput;
        if (MathF.Abs(inputScale - 1.0f) > 1e-6f)
        {
            modelInput = new Tensor(latentShape, DType.F32);
            backend.Scale(modelInput, scaledNoise, inputScale);
            scaledNoise.Dispose();
        }
        else
        {
            modelInput = scaledNoise;
        }

        float timestep = 950.0f; // First timestep for 20 steps, leading spacing
        List<(string name, float mean, float std, float min, float max, string shape)> csStats = new();

        void LogStats(string name, Tensor t)
        {
            float mean = ComputeMean(t);
            float std = ComputeStd(t);
            float tMin = ComputeMin(t);
            float tMax = ComputeMax(t);
            string shape = t.Shape.ToString();
            csStats.Add((name, mean, std, tMin, tMax, shape));
        }

        LogStats("unet_input", modelInput);
        LogStats("text_embeddings", textEmb);

        // === Instrumented Forward Pass via Reflection ===
        _output.WriteLine("Running instrumented UNet forward pass...\n");

        int batch = 1;
        int height = (int)modelInput.Shape[2];
        int width = (int)modelInput.Shape[3];
        UNetConfig config = unet.Config;

        // 1. Timestep embedding
        TimestepEmbedding timeEmbedding = GetField<TimestepEmbedding>(unet, "_timeEmbedding");
        Span<float> timesteps = stackalloc float[batch];
        timesteps.Fill(timestep);
        Tensor temb = timeEmbedding.Forward(backend, timesteps, batch);
        LogStats("time_embedding", temb);

        // 2. conv_in
        Tensor convInWeight = GetField<Tensor>(unet, "_convInWeight")!;
        Tensor? convInBias = GetField<Tensor?>(unet, "_convInBias");
        TensorShape convInShape = new(batch, config.ModelChannels, height, width);
        Tensor hidden = new(convInShape, DType.F32);
        backend.Conv2D(hidden, modelInput, convInWeight, convInBias, 1, 1, 1, 1);
        LogStats("conv_in", hidden);

        // 3. Down blocks
        DownBlock[] downBlocks = GetField<DownBlock[]>(unet, "_downBlocks");
        List<Tensor> allSkips = new() { hidden.To(hidden.Device) };

        for (int i = 0; i < downBlocks.Length; i++)
        {
            (Tensor downOut, List<Tensor> skips) = downBlocks[i].Forward(backend, hidden, temb, textEmb);
            hidden.Dispose();
            hidden = downOut;
            allSkips.AddRange(skips);

            LogStats($"down_block_{i}_output", hidden);

            // Log individual skip stats
            for (int j = 0; j < skips.Count; j++)
            {
                LogStats($"down_block_{i}_skip_{j}", skips[j]);
            }
        }

        // 4. Mid block
        UNetResNetBlock midResNet0 = GetField<UNetResNetBlock>(unet, "_midResNet0");
        CrossAttentionBlock midAttention = GetField<CrossAttentionBlock>(unet, "_midAttention");
        UNetResNetBlock midResNet1 = GetField<UNetResNetBlock>(unet, "_midResNet1");

        Tensor midRes0 = midResNet0.Forward(backend, hidden, temb);
        hidden.Dispose();
        LogStats("mid_block.resnets.0", midRes0);

        Tensor midAttn = midAttention.Forward(backend, midRes0, textEmb);
        midRes0.Dispose();
        LogStats("mid_block.attentions.0", midAttn);

        Tensor midRes1 = midResNet1.Forward(backend, midAttn, temb);
        midAttn.Dispose();
        LogStats("mid_block.resnets.1", midRes1);
        hidden = midRes1;

        // 5. Up blocks
        UpBlock[] upBlocks = GetField<UpBlock[]>(unet, "_upBlocks");
        for (int i = 0; i < upBlocks.Length; i++)
        {
            int skipsBefore = allSkips.Count;
            Tensor upOut = upBlocks[i].Forward(backend, hidden, temb, textEmb, allSkips);
            hidden.Dispose();
            hidden = upOut;
            int skipsConsumed = skipsBefore - allSkips.Count;
            LogStats($"up_block_{i}_output", hidden);
        }

        temb.Dispose();

        // 6. Final conv_norm_out → SiLU → conv_out
        Tensor normOutWeight = GetField<Tensor>(unet, "_normOutWeight")!;
        Tensor normOutBias = GetField<Tensor>(unet, "_normOutBias")!;
        Tensor convOutWeight = GetField<Tensor>(unet, "_convOutWeight")!;
        Tensor? convOutBias = GetField<Tensor?>(unet, "_convOutBias");

        int finalH = (int)hidden.Shape[2];
        int finalW = (int)hidden.Shape[3];
        int finalCh = config.ModelChannels;

        TensorShape finalShape = new(batch, finalCh, finalH, finalW);
        Tensor normOut = new(finalShape, DType.F32);
        backend.GroupNorm(normOut, hidden, normOutWeight, normOutBias, config.NormNumGroups, config.NormEps);
        hidden.Dispose();
        LogStats("conv_norm_out", normOut);

        Tensor siluOut = new(finalShape, DType.F32);
        backend.Silu(siluOut, normOut);
        normOut.Dispose();

        TensorShape outShape = new(batch, config.OutChannels, finalH, finalW);
        Tensor output = new(outShape, DType.F32);
        backend.Conv2D(output, siluOut, convOutWeight, convOutBias, 1, 1, 1, 1);
        siluOut.Dispose();
        LogStats("conv_out", output);
        LogStats("unet_output", output);

        // === Print results ===
        _output.WriteLine($"{"Layer",-40} {"Shape",-20} {"Mean",12} {"Std",12} {"Min",12} {"Max",12}");
        _output.WriteLine(new string('-', 108));
        foreach ((string name, float mean, float std, float min, float max, string shape) in csStats)
        {
            _output.WriteLine($"{name,-40} {shape,-20} {mean,12:F5} {std,12:F5} {min,12:F5} {max,12:F5}");
        }

        // === Compare against Python reference if available ===
        string pyIntermediatesPath = Path.Combine(DiagnosticsDir, "unet_intermediates.json");
        if (File.Exists(pyIntermediatesPath))
        {
            _output.WriteLine("\n\n=== Python Comparison ===");
            ComparePythonIntermediates(pyIntermediatesPath, csStats);
        }
        else
        {
            _output.WriteLine($"\nTo compare against Python, run: python tests/python-reference/dump_layer_outputs.py");
        }

        // Cleanup
        output.Dispose();
        modelInput.Dispose();
        textEmb.Dispose();
        foreach (Tensor skip in allSkips) skip.Dispose();
    }

