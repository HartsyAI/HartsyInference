    /// <summary>
    /// Runs a single UNet forward pass (no instrumentation) and checks that the output
    /// has reasonable statistics for epsilon prediction (mean near 0, std near 1).
    /// Does NOT require Python reference data.
    /// </summary>
    [Fact]
    public void UNetOutputSanityCheck()
    {
        if (!Directory.Exists(ModelDir))
        {
            _output.WriteLine($"SKIPPED: Model directory not found: {ModelDir}");
            return;
        }

        _output.WriteLine("Loading model...");
        UNet unet = new(UNetConfig.Sd15);
        using SafeTensorsLoader unetLoader = new();
        unetLoader.Load(Path.Combine(ModelDir, "unet", "diffusion_pytorch_model.fp16.safetensors"));
        unet.LoadWeights(CastWeightsToF32(unetLoader.GetAllTensors()));

        using CpuBackend backend = new();

        // Create a simple input: random noise as latent, zeros as text embedding
        TensorShape latentShape = new(1, 4, 32, 32);
        Tensor latent = Diffusion.Utilities.SeedGenerator.CreateNoise(latentShape, 42);

        // Simple zero text embedding [1, 77, 768]
        TensorShape embShape = new(1, 77, 768);
        Tensor textEmb = new(embShape, DType.F32);

        _output.WriteLine($"Input: mean={ComputeMean(latent):F6}, std={ComputeStd(latent):F6}");

        Tensor output = unet.Forward(backend, latent, 999.0f, textEmb);

        float outMean = ComputeMean(output);
        float outStd = ComputeStd(output);
        _output.WriteLine($"Output (t=999): mean={outMean:F6}, std={outStd:F6}");

        // For epsilon prediction at t=999 (high noise), the UNet should predict noise-like output
        // Mean should be near 0, std should be roughly order of magnitude 1
        _output.WriteLine($"\nSanity checks:");
        _output.WriteLine($"  |mean| < 1.0: {MathF.Abs(outMean) < 1.0f}");
        _output.WriteLine($"  0.01 < std < 10.0: {outStd > 0.01f && outStd < 10.0f}");
        _output.WriteLine($"  No NaN: {!float.IsNaN(outMean)}");
        _output.WriteLine($"  No Inf: {!float.IsInfinity(outStd)}");

        Assert.False(float.IsNaN(outMean), "UNet output contains NaN");
        Assert.False(float.IsInfinity(outStd), "UNet output contains Inf");
        Assert.True(outStd > 0.01f, $"UNet output std is too small: {outStd}");
        Assert.True(outStd < 10.0f, $"UNet output std is too large: {outStd}");

        output.Dispose();
        latent.Dispose();
        textEmb.Dispose();
    }

