    #region CFG Guidance Effectiveness Test

    /// <summary>
    /// Tests whether classifier-free guidance is producing meaningful conditioning by comparing
    /// unconditional and conditional noise predictions. If cond ≈ uncond, CFG is ineffective
    /// and images will be flat/featureless regardless of prompt.
    /// </summary>
    [Fact]
    public unsafe void CfgGuidanceEffectiveness()
    {
        if (!Directory.Exists(ModelDir))
        {
            _output.WriteLine($"SKIPPED: Model directory not found: {ModelDir}");
            return;
        }

        _output.WriteLine("Loading models...");
        using CpuBackend backend = new();

        // Load text encoder
        ClipTextEncoderConfig clipConfig = ClipTextEncoderConfig.Sd15;
        ClipTextEncoder textEncoder = new(clipConfig);
        using SafeTensorsLoader teLoader = new();
        teLoader.Load(Path.Combine(ModelDir, "text_encoder", "model.fp16.safetensors"));
        textEncoder.LoadWeights(CastWeightsToF32(teLoader.GetAllTensors()), "text_model");

        // Load UNet
        UNet unet = new(UNetConfig.Sd15);
        using SafeTensorsLoader unetLoader = new();
        unetLoader.Load(Path.Combine(ModelDir, "unet", "diffusion_pytorch_model.fp16.safetensors"));
        unet.LoadWeights(CastWeightsToF32(unetLoader.GetAllTensors()));

        // Encode both negative and positive prompts
        using HartsyInference.Tokenizers.ClipTokenizer tokenizer = new(
            Path.Combine(ModelDir, "tokenizer", "vocab.json"),
            Path.Combine(ModelDir, "tokenizer", "merges.txt"));

        int[] promptTokens = tokenizer.Encode("a painting of a cat sitting on a windowsill");
        int[] negativeTokens = tokenizer.Encode("blurry, bad quality");

        // Encode separately to see individual stats
        Tensor negEmb = textEncoder.Encode(backend, [negativeTokens]);
        Tensor posEmb = textEncoder.Encode(backend, [promptTokens]);

        _output.WriteLine($"\nText embedding stats:");
        _output.WriteLine($"  Negative: mean={ComputeMean(negEmb):F6}, std={ComputeStd(negEmb):F6}");
        _output.WriteLine($"  Positive: mean={ComputeMean(posEmb):F6}, std={ComputeStd(posEmb):F6}");

        // Compute embedding difference
        float embDiffMean = 0, embDiffStd = 0;
        {
            float* negPtr = (float*)negEmb.DataPointer;
            float* posPtr = (float*)posEmb.DataPointer;
            long count = negEmb.ElementCount;
            double sum = 0, sumSq = 0;
            for (long i = 0; i < count; i++)
            {
                double diff = posPtr[i] - negPtr[i];
                sum += diff;
                sumSq += diff * diff;
            }
            embDiffMean = (float)(sum / count);
            embDiffStd = (float)Math.Sqrt(sumSq / count - (sum / count) * (sum / count));
        }
        _output.WriteLine($"  Difference (pos-neg): mean={embDiffMean:F6}, std={embDiffStd:F6}");

        // Create step 0 input
        TensorShape latentShape = new(1, 4, 32, 32);
        Tensor noise = Diffusion.Utilities.SeedGenerator.CreateNoise(latentShape, 42);
        float timestep = 950.0f;

        _output.WriteLine($"\nRunning UNet passes at t={timestep}...");

        // Unconditional pass
        Tensor uncondPred = unet.Forward(backend, noise, timestep, negEmb);
        float uncondMean = ComputeMean(uncondPred);
        float uncondStd = ComputeStd(uncondPred);

        // Conditional pass
        Tensor condPred = unet.Forward(backend, noise, timestep, posEmb);
        float condMean = ComputeMean(condPred);
        float condStd = ComputeStd(condPred);

        _output.WriteLine($"\nUNet noise predictions:");
        _output.WriteLine($"  Uncond: mean={uncondMean:F6}, std={uncondStd:F6}");
        _output.WriteLine($"  Cond:   mean={condMean:F6}, std={condStd:F6}");

        // Compute prediction difference (what CFG amplifies)
        float* uncPtr = (float*)uncondPred.DataPointer;
        float* conPtr = (float*)condPred.DataPointer;
        int count2 = (int)latentShape.ElementCount;

        double diffSum = 0, diffSumSq = 0, diffAbsSum = 0;
        float maxDiff = 0;
        for (int i = 0; i < count2; i++)
        {
            float diff = conPtr[i] - uncPtr[i];
            diffSum += diff;
            diffSumSq += (double)diff * diff;
            diffAbsSum += MathF.Abs(diff);
            if (MathF.Abs(diff) > MathF.Abs(maxDiff)) maxDiff = diff;
        }
        float diffMean = (float)(diffSum / count2);
        float diffStd = (float)Math.Sqrt(diffSumSq / count2 - (diffSum / count2) * (diffSum / count2));
        float diffAbsMean = (float)(diffAbsSum / count2);

        _output.WriteLine($"\nCond - Uncond difference (what CFG amplifies by 7.5x):");
        _output.WriteLine($"  Mean: {diffMean:F6}");
        _output.WriteLine($"  Std:  {diffStd:F6}");
        _output.WriteLine($"  Abs mean: {diffAbsMean:F6}");
        _output.WriteLine($"  Max abs: {MathF.Abs(maxDiff):F6}");

        // CFG output: uncond + 7.5 * (cond - uncond)
        float cfgScale = 7.5f;
        double cfgSum = 0, cfgSumSq = 0;
        for (int i = 0; i < count2; i++)
        {
            float cfgVal = uncPtr[i] + cfgScale * (conPtr[i] - uncPtr[i]);
            cfgSum += cfgVal;
            cfgSumSq += (double)cfgVal * cfgVal;
        }
        float cfgMean = (float)(cfgSum / count2);
        float cfgStd = (float)Math.Sqrt(cfgSumSq / count2 - (cfgSum / count2) * (cfgSum / count2));

        _output.WriteLine($"\nCFG output (uncond + 7.5*(cond-uncond)):");
        _output.WriteLine($"  Mean: {cfgMean:F6}");
        _output.WriteLine($"  Std:  {cfgStd:F6}");

        // Python reference for comparison
        _output.WriteLine($"\nPython reference (from reference_stats.json):");
        _output.WriteLine($"  step0_noise_pred_uncond: mean=-0.003, std=0.996");
        _output.WriteLine($"  step0_noise_pred_cond:   mean=-0.004, std=0.997");

        // Verdict
        _output.WriteLine($"\n=== CFG Verdict ===");
        float condUncondRatio = diffStd / uncondStd;
        _output.WriteLine($"  cond-uncond std / uncond std = {condUncondRatio:F4}");

        if (diffStd < 0.001f)
        {
            _output.WriteLine("  PROBLEM: Cond and uncond predictions are nearly identical!");
            _output.WriteLine("  CFG guidance is NOT working. Cross-attention or text encoder has a bug.");
        }
        else if (diffStd < 0.01f)
        {
            _output.WriteLine("  WARNING: Cond-uncond difference is very small. Guidance signal may be weak.");
        }
        else
        {
            _output.WriteLine("  OK: Meaningful difference between cond and uncond predictions.");
            _output.WriteLine($"  The CFG guidance signal has std={diffStd:F6}, amplified to {diffStd * cfgScale:F6} by CFG.");
        }

        uncondPred.Dispose();
        condPred.Dispose();
        noise.Dispose();
        negEmb.Dispose();
        posEmb.Dispose();
    }

