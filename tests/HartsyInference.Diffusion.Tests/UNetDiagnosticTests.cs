            _output.WriteLine("SKIPPED: Layer reference not found. Run dump_layer_outputs.py first.");
            return;
        }
        if (!Directory.Exists(ModelDir))
        {
            _output.WriteLine($"SKIPPED: Model directory not found: {ModelDir}");
            return;
        }

        using CpuBackend backend = new();

        // Load UNet weights
        UNet unet = new(UNetConfig.Sd15);
        using SafeTensorsLoader unetLoader = new();
        unetLoader.Load(Path.Combine(ModelDir, "unet", "diffusion_pytorch_model.fp16.safetensors"));
        Dictionary<string, Tensor> weights = CastWeightsToF32(unetLoader.GetAllTensors());
        unet.LoadWeights(weights);

        // Load Python's exact input tensors
        TensorShape latentShape = new(1, 4, 32, 32);
        Tensor input = LoadBinaryTensor(Path.Combine(refDir, "unet_step0_input.bin"), latentShape);
        TensorShape embShape = new(1, 77, 768);
        Tensor textEmb = LoadBinaryTensor(Path.Combine(refDir, "unet_step0_text_emb.bin"), embShape);

        _output.WriteLine($"Input: mean={ComputeMean(input):F6}, std={ComputeStd(input):F6}");
        _output.WriteLine($"TextEmb: mean={ComputeMean(textEmb):F6}, std={ComputeStd(textEmb):F6}");

        float timestep = 950.0f;

        // Run individual layers manually using reflection to access private fields
        // 1. Time embedding
        TimestepEmbedding timeEmb = GetField<TimestepEmbedding>(unet, "_timeEmbedding");
        Span<float> timesteps = stackalloc float[1];
        timesteps[0] = timestep;
        Tensor temb = timeEmb.Forward(backend, timesteps, 1);
        CompareWithReference(layersDir, "time_embedding", temb, new TensorShape(1, 1280));

        // 2. Conv_in
        Tensor convInWeight = GetField<Tensor>(unet, "_convInWeight")!;
        Tensor convInBias = GetField<Tensor>(unet, "_convInBias")!;
        TensorShape convInOutShape = new(1, 320, 32, 32);
        Tensor hidden = new(convInOutShape, DType.F32);
        backend.Conv2D(hidden, input, convInWeight, convInBias, 1, 1, 1, 1);
        CompareWithReference(layersDir, "conv_in", hidden, convInOutShape);

        // 3. Run down blocks layer-by-layer with per-sublayer comparison
        DownBlock[] downBlocks = GetField<DownBlock[]>(unet, "_downBlocks");
        List<Tensor> allSkips = new() { hidden.To(hidden.Device) };

        _output.WriteLine("\n--- Down Blocks (manual sub-layer execution) ---");
        for (int bi = 0; bi < downBlocks.Length; bi++)
        {
            DownBlock db = downBlocks[bi];
            UNetResNetBlock[] resnets = GetField<UNetResNetBlock[]>(db, "_resnets");
            CrossAttentionBlock?[] attentions = GetField<CrossAttentionBlock?[]>(db, "_attentions");
            int numLayers = GetField<int>(db, "_numLayers");
            bool hasAttention = GetField<bool>(db, "_hasAttention");
            bool hasDownsample = GetField<bool>(db, "_hasDownsample");

            for (int li = 0; li < numLayers; li++)
            {
                Tensor resOut = resnets[li].Forward(backend, hidden, temb);
                if (li > 0 || bi > 0) hidden.Dispose();
                hidden = resOut;
                CompareWithReference(layersDir, $"down_blocks.{bi}.resnets.{li}", hidden, hidden.Shape);

                if (hasAttention && attentions[li] is not null)
                {
                    Tensor attnOut = attentions[li]!.Forward(backend, hidden, textEmb);
                    hidden.Dispose();
                    hidden = attnOut;
                    CompareWithReference(layersDir, $"down_blocks.{bi}.attentions.{li}", hidden, hidden.Shape);
                }

                allSkips.Add(hidden.To(hidden.Device));
            }

            if (hasDownsample)
            {
                Tensor dsWeight = GetField<Tensor>(db, "_downsampleWeight")!;
                Tensor dsBias = GetField<Tensor>(db, "_downsampleBias")!;
                int batch2 = (int)hidden.Shape[0];
                int ch = (int)hidden.Shape[1];
                int h2 = (int)hidden.Shape[2];
                int w2 = (int)hidden.Shape[3];
                TensorShape dsShape = new(batch2, ch, h2 / 2, w2 / 2);
                Tensor downsampled = new(dsShape, DType.F32);
                backend.Conv2D(downsampled, hidden, dsWeight, dsBias, 2, 2, 1, 1);
                hidden.Dispose();
                hidden = downsampled;
                CompareWithReference(layersDir, $"down_blocks.{bi}.downsamplers.0", hidden, hidden.Shape);
                allSkips.Add(hidden.To(hidden.Device));
            }
        }

        _output.WriteLine("\n--- Mid Block ---");

        // 4. Mid block
        UNetResNetBlock midResNet0 = GetField<UNetResNetBlock>(unet, "_midResNet0");
        CrossAttentionBlock midAttn = GetField<CrossAttentionBlock>(unet, "_midAttention");
        UNetResNetBlock midResNet1 = GetField<UNetResNetBlock>(unet, "_midResNet1");

        Tensor midRes0Out = midResNet0.Forward(backend, hidden, temb);
        hidden.Dispose();
        CompareWithReference(layersDir, "mid_block.resnets.0", midRes0Out, midRes0Out.Shape);

        Tensor midAttnOut = midAttn.Forward(backend, midRes0Out, textEmb);
        midRes0Out.Dispose();
        CompareWithReference(layersDir, "mid_block.attentions.0", midAttnOut, midAttnOut.Shape);

        Tensor midRes1Out = midResNet1.Forward(backend, midAttnOut, temb);
        midAttnOut.Dispose();
        CompareWithReference(layersDir, "mid_block.resnets.1", midRes1Out, midRes1Out.Shape);

        hidden = midRes1Out;

        // 5. Up blocks
        UpBlock[] upBlocks = GetField<UpBlock[]>(unet, "_upBlocks");
        for (int i = 0; i < upBlocks.Length; i++)
        {
            Tensor upOut = upBlocks[i].Forward(backend, hidden, temb, textEmb, allSkips);
            hidden.Dispose();
            hidden = upOut;
        }

        // 6. Final layers
        Tensor normOutWeight = GetField<Tensor>(unet, "_normOutWeight")!;
        Tensor normOutBias = GetField<Tensor>(unet, "_normOutBias")!;
        Tensor convOutWeight = GetField<Tensor>(unet, "_convOutWeight")!;
        Tensor convOutBias = GetField<Tensor>(unet, "_convOutBias")!;

        int finalH = (int)hidden.Shape[2];
        int finalW = (int)hidden.Shape[3];
        int finalCh = 320;

        TensorShape finalShape = new(1, finalCh, finalH, finalW);
        Tensor normOut = new(finalShape, DType.F32);
        backend.GroupNorm(normOut, hidden, normOutWeight, normOutBias, 32, 1e-6f);
        hidden.Dispose();
        CompareWithReference(layersDir, "conv_norm_out", normOut, finalShape);

        Tensor siluOut = new(finalShape, DType.F32);
        backend.Silu(siluOut, normOut);
        normOut.Dispose();

        TensorShape outShape = new(1, 4, finalH, finalW);
        Tensor output = new(outShape, DType.F32);
        backend.Conv2D(output, siluOut, convOutWeight, convOutBias, 1, 1, 1, 1);
        siluOut.Dispose();
        CompareWithReference(layersDir, "conv_out", output, outShape);

        _output.WriteLine($"\nFinal output: mean={ComputeMean(output):F6}, std={ComputeStd(output):F6}");

        // Cleanup
        temb.Dispose();
        input.Dispose();
        textEmb.Dispose();
        output.Dispose();
        foreach (Tensor skip in allSkips) skip.Dispose();
    }

    private unsafe void CompareWithReference(string layersDir, string layerName, Tensor csTensor, TensorShape expectedShape)
    {
        string fileName = layerName.Replace(".", "_") + ".bin";
        string refPath = Path.Combine(layersDir, fileName);

        if (!File.Exists(refPath))
        {
            _output.WriteLine($"  {layerName}: NO REFERENCE FILE ({fileName})");
            return;
        }

        Tensor pyTensor = LoadBinaryTensor(refPath, expectedShape);
        float* csPtr = (float*)csTensor.DataPointer;
        float* pyPtr = (float*)pyTensor.DataPointer;
        int count = (int)expectedShape.ElementCount;

        float maxAbsErr = 0f;
        double sumAbsErr = 0;
        int maxErrIdx = 0;

        for (int i = 0; i < count; i++)
        {
            float err = MathF.Abs(csPtr[i] - pyPtr[i]);
            sumAbsErr += err;
            if (err > maxAbsErr)
            {
                maxAbsErr = err;
                maxErrIdx = i;
            }
        }

        double avgAbsErr = sumAbsErr / count;
        float csMean = ComputeMean(csTensor);
        float csStd = ComputeStd(csTensor);
        float pyMean = ComputeMean(pyTensor);
        float pyStd = ComputeStd(pyTensor);

        string marker = avgAbsErr > 0.01 ? " <<<" : "";
        _output.WriteLine($"  {layerName,-40} avg_err={avgAbsErr:E3} max_err={maxAbsErr:E3} cs_std={csStd:F4} py_std={pyStd:F4}{marker}");

        if (avgAbsErr > 0.01)
        {
            _output.WriteLine($"    DIVERGENCE: C# val[{maxErrIdx}]={csPtr[maxErrIdx]:F6}, Py val[{maxErrIdx}]={pyPtr[maxErrIdx]:F6}");
            _output.WriteLine($"    C# mean={csMean:F6}, Py mean={pyMean:F6}");
        }

        pyTensor.Dispose();
    }

    private static unsafe Tensor LoadBinaryTensor(string path, TensorShape shape)
    {
        byte[] bytes = File.ReadAllBytes(path);
        long expectedBytes = shape.ElementCount * sizeof(float);
        if (bytes.Length != expectedBytes)
            throw new InvalidOperationException(
                $"Binary tensor size mismatch for {path}: got {bytes.Length} bytes, expected {expectedBytes} for shape {shape}");

        Tensor tensor = new(shape, DType.F32);
        fixed (byte* src = bytes)
        {
            Buffer.MemoryCopy(src, (void*)tensor.DataPointer, expectedBytes, expectedBytes);
        }
        return tensor;
    }

