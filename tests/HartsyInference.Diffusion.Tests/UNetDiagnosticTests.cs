    private void ComparePythonIntermediates(
        string jsonPath,
        List<(string name, float mean, float std, float min, float max, string shape)> csStats)
    {
        string json = File.ReadAllText(jsonPath);
        List<Dictionary<string, JsonElement>>? pyStats =
            JsonSerializer.Deserialize<List<Dictionary<string, JsonElement>>>(json);

        if (pyStats == null)
        {
            _output.WriteLine("Failed to parse Python intermediates JSON.");
            return;
        }

        // Build lookup from Python stats
        Dictionary<string, (double mean, double std, double min, double max)> pyLookup = new();
        foreach (Dictionary<string, JsonElement> entry in pyStats)
        {
            if (!entry.TryGetValue("name", out JsonElement nameEl)) continue;
            string? name = nameEl.GetString();
            if (name == null || !entry.ContainsKey("mean")) continue;

            pyLookup[name] = (
                entry["mean"].GetDouble(),
                entry["std"].GetDouble(),
                entry["min"].GetDouble(),
                entry["max"].GetDouble()
            );
        }

        // Map C# names to Python hook names for comparison
        Dictionary<string, string> nameMap = BuildNameMap();

        _output.WriteLine($"\n{"C# Layer",-40} {"C# Std",10} {"Py Std",10} {"Ratio",10} {"Match?",8}");
        _output.WriteLine(new string('-', 80));

        foreach ((string name, float mean, float std, float min, float max, string shape) in csStats)
        {
            // Try direct name match or mapped name
            string pyName = nameMap.TryGetValue(name, out string? mapped) ? mapped : name;

            if (pyLookup.TryGetValue(pyName, out (double mean, double std, double min, double max) py))
            {
                double ratio = std / py.std;
                bool match = Math.Abs(ratio - 1.0) < 0.05; // Within 5%
                string matchStr = match ? "OK" : "DIVERGE";
                _output.WriteLine($"{name,-40} {std,10:F5} {py.std,10:F5} {ratio,10:F4} {matchStr,8}");

                if (!match)
                {
                    _output.WriteLine($"  ** MISMATCH: C# mean={mean:F5} vs Py mean={py.mean:F5}");
                    _output.WriteLine($"  ** MISMATCH: C# std={std:F5} vs Py std={py.std:F5}");
                }
            }
        }
    }

    /// <summary>Maps C# intermediate names to Python forward hook names.</summary>
    private static Dictionary<string, string> BuildNameMap()
    {
        Dictionary<string, string> map = new()
        {
            ["unet_input"] = "unet_input",
            ["text_embeddings"] = "text_embeddings",
            ["time_embedding"] = "time_embedding",
            ["conv_in"] = "conv_in",
            ["mid_block.resnets.0"] = "mid_block.resnets.0",
            ["mid_block.attentions.0"] = "mid_block.attentions.0",
            ["mid_block.resnets.1"] = "mid_block.resnets.1",
            ["conv_norm_out"] = "conv_norm_out",
            ["conv_out"] = "conv_out",
            ["unet_output"] = "unet_output",
        };

        // Down blocks: C# "down_block_0_output" -> Python hook captures resnets/attentions individually
        // The Python hooks capture each resnet and attention output separately
        // C# captures the block output (after downsample if present)
        for (int i = 0; i < 4; i++)
        {
            // Map up block outputs
            map[$"up_block_{i}_output"] = $"up_blocks.{i}.upsamplers.0"; // Last op is upsample (except block 0 which has no upsample)
        }

        return map;
    }

