    /// <summary>
    /// Runs C# UNet layer-by-layer using Python's exact input tensors and compares
    /// each layer's output element-wise against Python reference binaries.
    /// This isolates the FIRST layer where significant divergence appears.
    /// </summary>
    [Fact]
    public unsafe void LayerByLayerComparisonWithPythonInputs()
    {
        string layersDir = Path.Combine(DiagnosticsDir, "reference_tensors", "layers");
        string refDir = Path.Combine(DiagnosticsDir, "reference_tensors");

        if (!File.Exists(Path.Combine(layersDir, "index.json")))
