/// <summary>Gate S7: the C# ABC serializer against the released implementation's own output, character for character.
///
/// <para>String-exact rather than tolerant, because the output is a dialect an external validator parses. A bar
/// written as two tied halves instead of one note, or a rest bar written out instead of folded into <c>Z</c>,
/// is the same music and a different document.</para>
///
/// <para>The fixture's event streams are hand-built. A real transcription is four-four throughout, never carries
/// a pickup, never changes key mid-bar and never uses a flat-root slash chord, so it would leave most of the
/// serializer untested; each case here is aimed at one path that a decoded song would not reach.</para>
///
/// <para>Needs no checkpoint, backend or GPU — the fixture is regenerated by
/// <c>tests/python-reference/dump_sheetsage2_abc_reference.py</c>.</para></summary>
public sealed class SheetSage2AbcParityTests
{
    private static readonly JsonElement Reference = LoadReference();

    private static readonly Regex HeaderLine = new("^[A-Za-z]:", RegexOptions.None, TimeSpan.FromSeconds(2));

    private static readonly Regex QuotedText = new("\"[^\"]*\"", RegexOptions.None, TimeSpan.FromSeconds(2));

    public static TheoryData<string> CaseNames()
    {
        TheoryData<string> names = [];
        foreach (JsonProperty entry in Reference.GetProperty("cases").EnumerateObject())
        {
            names.Add(entry.Name);
        }
        return names;
    }

    private static JsonElement LoadReference()
    {
        string path = Path.Combine(AppContext.BaseDirectory, "python-reference", "sheetsage2_reference", "abc.json");
        if (!File.Exists(path))
        {
            // Fall back to the source tree when the fixture was not copied next to the test binary.
            DirectoryInfo? dir = new(AppContext.BaseDirectory);
            while (dir is not null && !Directory.Exists(Path.Combine(dir.FullName, "tests", "python-reference")))
            {
                dir = dir.Parent;
            }
            path = Path.Combine(dir?.FullName ?? ".", "tests", "python-reference", "sheetsage2_reference", "abc.json");
        }
        return JsonDocument.Parse(File.ReadAllText(path)).RootElement.Clone();
    }

