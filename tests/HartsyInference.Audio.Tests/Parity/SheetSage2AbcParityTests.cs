        Assert.Equal(want.GetProperty("melodyOnly").GetString(), AbcSerializer.EventsToAbc(events, duration));
        Assert.Equal(want.GetProperty("full").GetString(),
            AbcSerializer.EventsToAbc(events, duration, melodyOnly: false));
    }

