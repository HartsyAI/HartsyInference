    /// <summary>The inferred bar table and its diagnostics, which never reach the ABC text and so cannot be
    /// caught by comparing it — a bar wrongly flagged as a pickup renders identically until it does not.</summary>
    [Theory]
    [MemberData(nameof(CaseNames))]
    public void ResolvedScore_MatchesTheReference(string name)
    {
        JsonElement want = Reference.GetProperty("cases").GetProperty(name).GetProperty("score");
        JsonElement caseData = Reference.GetProperty("cases").GetProperty(name);
        RebuiltAbcScore score = AbcSerializer.BuildScore(ReadEvents(caseData.GetProperty("events")),
            caseData.GetProperty("duration").GetDouble(), melodyOnly: false);

        Assert.Equal(want.GetProperty("beatCount").GetInt32(), score.Beats.Count);
        Assert.Equal(want.GetProperty("subbeatCount").GetInt32(), score.SubbeatTimes.Length);
        Assert.Equal(want.GetProperty("unitDenominator").GetInt32(), AbcSerializer.AbcUnitDenominator(score));
        Assert.Equal(want.GetProperty("tempo").GetDouble(), AbcSerializer.EstimateTempo(score), 9);
        Assert.Equal([.. want.GetProperty("diagnostics").EnumerateArray().Select(e => e.GetString()!)],
            score.Diagnostics);

        JsonElement measures = want.GetProperty("measures");
        Assert.Equal(measures.GetArrayLength(), score.Measures.Count);
        int index = 0;
        foreach (JsonElement expected in measures.EnumerateArray())
        {
            Measure got = score.Measures[index++];
            Assert.Equal(expected.GetProperty("index").GetInt32(), got.Index);
            Assert.Equal(expected.GetProperty("startBeat").GetInt32(), got.StartBeat);
            Assert.Equal(expected.GetProperty("endBeat").GetInt32(), got.EndBeat);
            Assert.Equal(expected.GetProperty("numerator").GetInt32(), got.Numerator);
            Assert.Equal(expected.GetProperty("denominator").GetInt32(), got.Denominator);
            Assert.Equal(expected.GetProperty("pickup").GetBoolean(), got.Pickup);
            Assert.Equal(expected.GetProperty("partial").GetBoolean(), got.Partial);
            Assert.Equal(expected.GetProperty("inferred").GetBoolean(), got.Inferred);
            AssertNullableInt(expected.GetProperty("notatedNumerator"), got.NotatedNumerator);
            AssertNullableInt(expected.GetProperty("notatedDenominator"), got.NotatedDenominator);
            Assert.Equal(expected.GetProperty("padBefore").GetBoolean(), got.PadBefore);
            Assert.Equal(expected.GetProperty("abcNumerator").GetInt32(), got.AbcNumerator);
            Assert.Equal(expected.GetProperty("abcDenominator").GetInt32(), got.AbcDenominator);
        }

        AssertDoubles(want.GetProperty("subbeatTimes"), score.SubbeatTimes);
        AssertDoubles(want.GetProperty("subbeatQuarters"), score.SubbeatQuarters);
        Assert.Equal(ExpandInts(want.GetProperty("subbeatDenominators")), score.SubbeatDenominators);
        Assert.Equal(ExpandStrings(want.GetProperty("keyArr")), score.KeyArr);
        Assert.Equal(ExpandStrings(want.GetProperty("chordArr")), score.ChordArr);
        foreach (JsonProperty voice in want.GetProperty("voiceArrs").EnumerateObject())
        {
            Assert.Equal(ExpandInts(voice.Value), score.VoiceArrs[voice.Name]);
        }

        JsonElement structure = want.GetProperty("structureEvents");
        Assert.Equal(structure.GetArrayLength(), score.StructureEvents.Count);
        int event_ = 0;
        foreach (JsonElement expected in structure.EnumerateArray())
        {
            (int subbeat, string label) = score.StructureEvents[event_++];
            Assert.Equal(expected[0].GetInt32(), subbeat);
            Assert.Equal(expected[1].GetString(), label);
        }
    }

