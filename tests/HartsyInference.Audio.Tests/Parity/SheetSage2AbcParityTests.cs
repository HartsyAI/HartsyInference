    /// <summary>Gate S7b: melody mode is not a chord strip.
    ///
    /// <para>A downstream UI wanted to render once and hide the chords client-side. It cannot. Chords change how
    /// the rest of the score is spelled, three ways: a chord change inside a sustained note splits it into tied
    /// pieces, a bar carrying a chord symbol cannot be folded into a multi-bar <c>Z</c> rest, and the same
    /// applies within a bar to a rest that a chord change cuts in two. Whether any case is affected depends
    /// entirely on where the chords land, so the fixture pins the answer per case and this asserts the port
    /// reproduces it either way — including the cases where the two DO coincide, since a port that always
    /// diverged would otherwise look correct.</para></summary>
    [Theory]
    [MemberData(nameof(CaseNames))]
    public void StrippingChordsOutOfTheFullRendering_MatchesTheReference(string name)
    {
        JsonElement want = Reference.GetProperty("cases").GetProperty(name);
        List<TimedScoreEvent> events = ReadEvents(want.GetProperty("events"));
        double duration = want.GetProperty("duration").GetDouble();
        string melodyOnly = AbcSerializer.EventsToAbc(events, duration);
        string stripped = StripChords(AbcSerializer.EventsToAbc(events, duration, melodyOnly: false));
        Assert.Equal(want.GetProperty("strippedFull").GetString(), stripped);
        Assert.Equal(want.GetProperty("strippedFullEqualsMelodyOnly").GetBoolean(), stripped == melodyOnly);
    }

    /// <summary>The strongest single statement this gate makes: 55 events the released model really produced
    /// from thirty seconds of solo piano, rendered both ways, character for character.
    ///
    /// <para>Kept as a named test on top of the theory above so that dropping the case from the fixture fails
    /// loudly instead of quietly shrinking the gate. It is one window, so it says nothing about the stitching
    /// seam; what it does say is that the port handles the event shapes the model actually emits — events
    /// carrying a bar position but no meter, a chord track opening on no-chord, a key change, both tracks and
    /// multi-bar rests — rather than the ones a hand-built stream imagines.</para></summary>
    [Fact]
