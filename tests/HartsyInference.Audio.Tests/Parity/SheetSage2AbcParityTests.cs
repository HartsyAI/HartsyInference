    /// <summary>Notes that collide on one voice are trimmed, never refused.
    ///
    /// <para>The trim pass runs before quantization and leaves every span on a voice disjoint, so the melody
    /// array's own overlap guard cannot be reached through <see cref="AbcSerializer.EventsToAbc"/> at all — it
    /// defends a score assembled by hand. Two notes sharing an onset lose the one the sort puts first, which is
    /// the lower pitch: it is cut to zero length against the other's start and dropped. The
    /// <c>overlapping_notes</c> case pins the resulting voice array, so this only has to establish that nothing
    /// is refused.</para></summary>
    [Fact]
    public void NotesThatCollideOnOneVoice_AreTrimmedRatherThanRefused()
    {
        List<TimedScoreEvent> events =
        [
            Beat(0.0, 4, 4, 0, key: "C:major",
                melody: [new TimedScoreNote(60, 0, 1.0), new TimedScoreNote(64, 0, 1.0)]),
            Beat(0.5, 4, 4, 2), Beat(1.0, 4, 4, 4), Beat(1.5, 4, 4, 6), Beat(2.0, 4, 4, 0),
        ];
        RebuiltAbcScore score = AbcSerializer.BuildScore(events, 2.5);
        // 64 * 2 + 3 is the onset code for the surviving pitch; the lower note left nothing behind.
        Assert.Equal((64 * 2) + 3, score.VoiceArrs["Vocal"][0]);
        Assert.DoesNotContain((60 * 2) + 3, score.VoiceArrs["Vocal"]);
    }

