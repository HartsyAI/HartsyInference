    private static TimedScoreEvent Beat(double time, int numerator, int denominator, int eighth,
        string? key = null, string? chord = null, string? structure = null, TimedScoreNote[]? melody = null)
        => new()
        {
            Time = time,
            Rhythm = new ScoreRhythm((numerator, denominator), eighth),
            Key = key,
            Chord = chord,
            Structure = structure,
            Melody = melody,
        };

    /// <summary>Removes quoted chord symbols, leaving header and comment lines alone. The voice headers carry
    /// quotes of their own, so a blanket substitution would mangle them into <c>name=</c>.</summary>
    private static string StripChords(string text)
    {
        string[] lines = text.Split('\n');
        for (int i = 0; i < lines.Length; i++)
        {
            if (lines[i].StartsWith('%') || HeaderLine.IsMatch(lines[i])) continue;
            lines[i] = QuotedText.Replace(lines[i], "");
        }
        return string.Join("\n", lines);
    }

    private static List<TimedScoreEvent> ReadEvents(JsonElement events)
    {
        List<TimedScoreEvent> result = [];
        foreach (JsonElement item in events.EnumerateArray())
        {
            JsonElement meter = item.GetProperty("meter");
            JsonElement eighth = item.GetProperty("eighthPosition");
            ScoreRhythm? rhythm = null;
            if (meter.ValueKind != JsonValueKind.Null || eighth.ValueKind != JsonValueKind.Null)
            {
                rhythm = new ScoreRhythm(
                    meter.ValueKind == JsonValueKind.Null ? null : (meter[0].GetInt32(), meter[1].GetInt32()),
                    eighth.ValueKind == JsonValueKind.Null ? null : eighth.GetInt32());
            }
            List<TimedScoreNote> melody = [];
            foreach (JsonElement note in item.GetProperty("melody").EnumerateArray())
            {
                melody.Add(new TimedScoreNote(note.GetProperty("pitch").GetInt32(),
                    note.GetProperty("track").GetInt32(), note.GetProperty("endTime").GetDouble()));
            }
            result.Add(new TimedScoreEvent
            {
                Time = item.GetProperty("time").GetDouble(),
                Rhythm = rhythm,
                Key = Text(item, "key"),
                Structure = Text(item, "structure"),
                Chord = Text(item, "chord"),
                Melody = melody.Count > 0 ? melody : null,
            });
        }
        return result;
    }

    private static string? Text(JsonElement item, string name)
    {
        JsonElement value = item.GetProperty(name);
        return value.ValueKind == JsonValueKind.Null ? null : value.GetString();
    }

    private static void AssertNullableInt(JsonElement expected, int? actual)
    {
        if (expected.ValueKind == JsonValueKind.Null) Assert.Null(actual);
        else Assert.Equal(expected.GetInt32(), actual);
    }

    private static void AssertDoubles(JsonElement expected, double[] actual)
    {
        Assert.Equal(expected.GetArrayLength(), actual.Length);
        int index = 0;
        foreach (JsonElement value in expected.EnumerateArray())
        {
            Assert.Equal(value.GetDouble(), actual[index++], 12);
        }
    }

    /// <summary>Expands the fixture's run-length encoding of a per-subbeat array.</summary>
    private static int[] ExpandInts(JsonElement runs)
    {
        List<int> values = [];
        foreach (JsonElement run in runs.EnumerateArray())
        {
            values.AddRange(Enumerable.Repeat(run[1].GetInt32(), run[0].GetInt32()));
        }
        return [.. values];
    }

    private static string[] ExpandStrings(JsonElement runs)
    {
        List<string> values = [];
        foreach (JsonElement run in runs.EnumerateArray())
        {
            values.AddRange(Enumerable.Repeat(run[1].GetString()!, run[0].GetInt32()));
        }
        return [.. values];
    }
