using HartsyInference.Core.Tensors;
using HartsyInference.Tests.Common;
using Xunit;
using Xunit.Abstractions;

namespace HartsyInference.Cuda.Tests;

/// <summary>A device below the sm_80 kernel baseline (a Turing card) must still construct a backend: modules whose PTX targets a
/// newer architecture are skipped instead of failing the JIT, the sm_70/sm_75 modules still load, and a launch of a skipped
/// kernel names what was skipped. An Ampere-or-newer card stands in for the older one through the test gate.</summary>
[Collection("CudaSerial")]
public sealed class ArchitectureGateTests
{
    private readonly ITestOutputHelper _output;
    public ArchitectureGateTests(ITestOutputHelper output) => _output = output;

    [Theory]
    [InlineData(".target sm_80", 80)]
    [InlineData(".target sm_75", 75)]
    [InlineData(".target sm_120a", 120)]
    [InlineData(".target sm_70, texmode_independent", 70)]
    [InlineData("// no target directive", 0)]
    public void ReadTargetSm_ParsesTheTargetDirective(string directive, int expected)
    {
        string path = Path.Combine(Path.GetTempPath(), $"archgate_{Guid.NewGuid():N}.ptx");
        try
        {
            File.WriteAllLines(path, ["//", "// Generated by test", "//", "", ".version 9.0", directive, ".address_size 64"]);
            Assert.Equal(expected, CudaModule.ReadTargetSm(path));
        }
        finally
        {
            File.Delete(path);
        }
    }

    [Fact]
    public void EveryShippedBaselinePtx_TargetsTheBaselineOrOlder()
    {
        string[] baseline = Directory.GetFiles(PtxDir(), "*.ptx").Where(path => Path.GetFileName(path).Count(c => c == '.') == 1).ToArray();
        Assert.NotEmpty(baseline);
        foreach (string path in baseline)
        {
            int target = CudaModule.ReadTargetSm(path);
            Assert.True(target is > 0 and <= CudaKernels.BaselineSm, $"{Path.GetFileName(path)} targets sm_{target}.");
        }
    }

    [Trait("Category", "GpuIntegration")]
    [Fact]
    public void BelowTheBaseline_SkipsNewerModules_KeepsOlderOnes_AndALaunchNamesWhatWasSkipped()
    {
        if (!CudaContext.IsAvailable()) { _output.WriteLine("SKIPPED: CUDA unavailable"); return; }

        int previous = CudaKernels.GateSmForTests;
        try
        {
            CudaKernels.GateSmForTests = 75;
            using CudaBackend backend = new(0, PtxDir());

            IReadOnlyList<string> skipped = backend.SkippedKernelModules;
            _output.WriteLine($"skipped {skipped.Count}: {string.Join(", ", skipped)}");
            Assert.All(skipped, module => Assert.True(TargetOf(module) > 75, module));
            Assert.Contains(skipped, module => module.StartsWith("flash_attn_f16 ", StringComparison.Ordinal));
            Assert.Contains(skipped, module => module.StartsWith("sage_attn_int8 ", StringComparison.Ordinal));
            Assert.Contains(skipped, module => module.StartsWith("moe_prefill ", StringComparison.Ordinal));
            Assert.DoesNotContain(skipped, module => module.StartsWith("elementwise_f32 ", StringComparison.Ordinal));
            Assert.DoesNotContain(skipped, module => module.StartsWith("dequant_q4_k_to_f16 ", StringComparison.Ordinal));
            Assert.False(backend.Kernels!.HasFlashAttnF16);
            Assert.False(backend.Kernels.HasSageAttentionKernels);
            Assert.False(backend.Kernels.HasMoePrefillKernels);

            // elementwise_f32 is sm_70 PTX, so its kernels still load and compute.
            const int n = 1000;
            using Tensor a = Filled(n, i => i * 0.5f);
            using Tensor b = Filled(n, i => 3f - i);
            using Tensor sum = new(new TensorShape(n), DType.F32);
            backend.Add(sum, a, b);
            backend.Sync();
            ReadOnlySpan<float> values = sum.AsSpan<float>();
            for (int i = 0; i < n; i++)
                Assert.Equal(i * 0.5f + (3f - i), values[i]);

            // wan_rope has a Turing build, so it binds. The note an invalid-handle error would carry names the optional skips.
            Assert.DoesNotContain(skipped, module => module.StartsWith("wan_rope ", StringComparison.Ordinal));
            string? note = CudaKernels.SkippedModulesNoteForCurrentContext();
            _output.WriteLine(note ?? "(no note)");
            Assert.NotNull(note);
            Assert.Contains($"cannot load {skipped.Count} kernel module(s)", note, StringComparison.Ordinal);
            Assert.Contains("have fallback paths", note, StringComparison.Ordinal);
        }
        finally
        {
            CudaKernels.GateSmForTests = previous;
        }
    }

    [Trait("Category", "GpuIntegration")]
    [Fact]
    public void InvalidHandleNote_BelongsToTheSkippingContext_AndLeavesWithItsTables()
    {
        if (!CudaContext.IsAvailable()) { _output.WriteLine("SKIPPED: CUDA unavailable"); return; }
        // The ungated table must skip nothing, which only a card at the baseline can show.
        if (CudaContext.QuerySm(0) < CudaKernels.BaselineSm) { _output.WriteLine("SKIPPED: this card is below the baseline"); return; }

        int previous = CudaKernels.GateSmForTests;
        try
        {
            CudaKernels.GateSmForTests = 75;
            CudaBackend gated = new(0, PtxDir());
            CudaKernels.GateSmForTests = previous;
            try
            {
                // The constructing thread has the gated table's context current.
                Assert.Contains("cannot load", Assert.Throws<CudaException>(() => 400.ThrowOnError()).Message, StringComparison.Ordinal);
            }
            finally
            {
                gated.Dispose();
            }

            using CudaBackend ungated = new(0, PtxDir());
            Assert.DoesNotContain("cannot load", Assert.Throws<CudaException>(() => 400.ThrowOnError()).Message, StringComparison.Ordinal);
        }
        finally
        {
            CudaKernels.GateSmForTests = previous;
        }
    }

    [Trait("Category", "GpuIntegration")]
    [Fact]
    public void AtOrAboveTheBaseline_NothingIsSkipped()
    {
        if (!CudaContext.IsAvailable()) { _output.WriteLine("SKIPPED: CUDA unavailable"); return; }
        if (CudaContext.QuerySm(0) < CudaKernels.BaselineSm) { _output.WriteLine("SKIPPED: this card is below the baseline"); return; }

        using CudaBackend backend = new(0, PtxDir());

        Assert.Empty(backend.SkippedKernelModules);
    }

    private static int TargetOf(string module)
    {
        int at = module.LastIndexOf("(sm_", StringComparison.Ordinal);
        return int.Parse(module.AsSpan(at + 4, module.Length - at - 5), System.Globalization.CultureInfo.InvariantCulture);
    }

    private static Tensor Filled(int count, Func<int, float> value)
    {
        Tensor tensor = new(new TensorShape(count), DType.F32);
        Span<float> data = tensor.AsSpan<float>();
        for (int i = 0; i < count; i++)
            data[i] = value(i);
        return tensor;
    }

    private static string PtxDir()
    {
        string dir = Path.Combine(AppContext.BaseDirectory, "Ptx");
        if (!Directory.Exists(dir))
            dir = Path.Combine(RepoRoot.Path, "src", "HartsyInference.Cuda", "Ptx");
        return dir;
    }
}
