    [Fact]
    public void Edges_AreTheOnesOpenCvCannyFindsInAnImageWithEveryGradientDirectionAndABorderEdge()
    {
        byte[] gray = [.. Image.Split(',').Select(byte.Parse)];
        bool[] expected = [.. OpenCvEdges.Select(c => c == '1')];

        bool[] edges = PaintImageFilters.Edges(gray, 28, 28, 30, 80);

        Assert.Equal(784, gray.Length);
        Assert.Equal(106, expected.Count(e => e));
        string difference = string.Join(", ", Enumerable.Range(0, edges.Length).Where(i => edges[i] != expected[i]).Select(i => $"({i % 28},{i / 28})"));
        Assert.True(difference.Length == 0, $"differs from OpenCV at {difference}");
    }
