"""Reference vectors for the decode-with-lengths reference test, from Comfy Kitchen's torch definition.

Run with the isolated Kitchen environment (README, "Isolated Kitchen environment"), on CPU:

    python -s benchmarks/attention/kitchen_decode_vectors.py --out tests/HartsyInference.Core.Tests/Backends/DecodeLengthsKitchenVectors.cs

On CPU tensors the Kitchen's flash_attention_decode_gqa runs its torch definition for every dtype and head dim. Each case
builds its inputs with a generator the C# test repeats bit for bit (for BF16, rounded to nearest even as torch rounds),
and keeps the output (every CHANNEL_STEP-th value of each row, widened to F32) and the log-sum-exp.
"""
import argparse
import hashlib
import importlib.metadata
import struct
import sys
from pathlib import Path

import torch

import comfy_kitchen.flash_attention as kitchen

CHANNEL_STEP = 8


def uniform(count, seed):
    """count values in [-1, 1) from a 32-bit LCG: exact in F32, and trivially the same in C#."""
    state = seed & 0xFFFFFFFF
    values = []
    for _ in range(count):
        state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
        values.append(((state >> 8) & 0xFFFF) / 32768.0 - 1.0)
    return torch.tensor(values, dtype=torch.float32)


def cases():
    # name, dtype, batch, heads, kv heads, head dim, step rows, cache capacity, lengths per batch, causal
    yield "CausalStaircase", torch.float32, 1, 4, 2, 64, 5, 48, [40], True
    yield "CausalShortAndOverlongLengths", torch.float32, 2, 4, 2, 64, 6, 32, [3, 99], True
    yield "PlainDecodeOverBatches", torch.float32, 3, 6, 2, 128, 1, 24, [1, 17, 0], True
    yield "PrefixOnly", torch.float32, 2, 4, 1, 64, 4, 28, [21, 0], False
    yield "Bf16CausalHeadDim256", torch.bfloat16, 1, 4, 2, 256, 3, 40, [37], True
    yield "Bf16PrefixOnlyOverBatches", torch.bfloat16, 2, 4, 2, 64, 2, 32, [12, 30], False


def run(dtype, batch, heads, kv_heads, dim, rows, capacity, lengths, causal, seed):
    q = uniform(batch * heads * rows * dim, seed).reshape(batch, heads, rows, dim).to(dtype)
    k = uniform(batch * kv_heads * capacity * dim, seed + 1).reshape(batch, kv_heads, capacity, dim).to(dtype)
    v = uniform(batch * kv_heads * capacity * dim, seed + 2).reshape(batch, kv_heads, capacity, dim).to(dtype)
    out, lse = kitchen.flash_attention_decode_gqa(q, k, v, torch.tensor(lengths, dtype=torch.int32), return_lse=True, causal=causal)
    assert out.dtype == dtype and out.shape == (batch, rows, heads * dim) and lse.shape == (batch, heads, rows)
    return out.float()[..., ::CHANNEL_STEP].contiguous(), lse.float().contiguous()


def literal(name, tensor):
    bits = struct.unpack(f"<{tensor.numel()}I", tensor.numpy().tobytes())
    lines = [f"    public static readonly uint[] {name} =", "    ["]
    for i in range(0, len(bits), 8):
        lines.append("        " + " ".join(f"0x{b:08X}," for b in bits[i:i + 8]))
    lines.append("    ];")
    lines.append("")
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    source = Path(kitchen.__file__)
    digest = hashlib.sha256(source.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
    lines = [
        "// Generated by benchmarks/attention/kitchen_decode_vectors.py; do not edit by hand.",
        f"// Comfy Kitchen {importlib.metadata.version('comfy_kitchen')}, flash_attention.py sha256 {digest} (line endings normalized),",
        f"// torch {torch.__version__.split('+')[0]} on CPU.",
        "namespace HartsyInference.Core.Tests.Backends;",
        "",
        "/// <summary>Outputs of Comfy Kitchen's torch decode definition for the cases DecodeLengthsReferenceTests rebuilds: per",
        "/// case the output <c>[batch, row, heads × headDim]</c>, every ChannelStep-th value of each row, widened to F32, and the",
        "/// log-sum-exp <c>[batch, head, row]</c>, as F32 bits.</summary>",
        "internal static class DecodeLengthsKitchenVectors",
        "{",
        f"    public const int ChannelStep = {CHANNEL_STEP};",
        "",
    ]
    count = 0
    for index, (name, *shape) in enumerate(cases()):
        out, lse = run(*shape, seed=5000 + 100 * index)
        lines += literal(name, out)
        lines += literal(name + "Lse", lse)
        count += 1
    lines[-1] = "}"
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out}: {count} cases", file=sys.stderr)


if __name__ == "__main__":
    main()
