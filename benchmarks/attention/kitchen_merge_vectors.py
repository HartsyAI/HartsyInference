"""Reference vectors for the decode merge reference test, from Comfy Kitchen's torch definitions.

Run with the isolated Kitchen environment (README, "Isolated Kitchen environment"), on CPU:

    python -s benchmarks/attention/kitchen_merge_vectors.py --out tests/HartsyInference.Core.Tests/Backends/DecodeMergeKitchenVectors.cs

On CPU tensors the Kitchen's flash_attention_decode_gqa, flash_attention_decode_tree_merge and
flash_attention_decode_step_merge run their torch definitions. Each case builds its inputs with a generator the C# test
repeats bit for bit, runs a prefix-only decode with its log-sum-exp, folds the step's own rows in, and keeps the merged
output (every CHANNEL_STEP-th value of each row) and the prefix log-sum-exp.
"""
import argparse
import hashlib
import importlib.metadata
import struct
import sys
from pathlib import Path

import torch

import comfy_kitchen.flash_attention as kitchen

CHANNEL_STEP = 8


def uniform(count, seed):
    """count values in [-1, 1) from a 32-bit LCG: exact in F32, and trivially the same in C#."""
    state = seed & 0xFFFFFFFF
    values = []
    for _ in range(count):
        state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
        values.append(((state >> 8) & 0xFFFF) / 32768.0 - 1.0)
    return torch.tensor(values, dtype=torch.float32)


def cases():
    # name, batch, heads, kv heads, head dim, step rows, cache capacity, valid lengths per batch, mask (None = causal step)
    yield "StepCausal", 1, 4, 2, 64, 5, 48, [40], None
    yield "StepGroupedBatches", 2, 6, 2, 64, 4, 40, [33, 17], None
    yield "StepSingleRow", 1, 4, 4, 128, 1, 32, [32], None
    yield "TreeBranches", 1, 4, 2, 64, 6, 48, [29], [0b000001, 0b000011, 0b000101, 0b001011, 0b010101, 0b100101]
    yield "TreeWithARowThatSeesNoStepRow", 1, 4, 1, 64, 4, 24, [24], [0b0001, 0b0000, 0b0101, 0b1101]
    yield "StepOverAnEmptyPrefix", 2, 4, 2, 64, 3, 16, [0, 9], None


def run(batch, heads, kv_heads, dim, rows, capacity, lengths, mask, seed):
    q = uniform(batch * heads * rows * dim, seed).reshape(batch, heads, rows, dim)
    cache_k = uniform(batch * kv_heads * capacity * dim, seed + 1).reshape(batch, kv_heads, capacity, dim)
    cache_v = uniform(batch * kv_heads * capacity * dim, seed + 2).reshape(batch, kv_heads, capacity, dim)
    step_k = uniform(batch * kv_heads * rows * dim, seed + 3).reshape(batch, kv_heads, rows, dim)
    step_v = uniform(batch * kv_heads * rows * dim, seed + 4).reshape(batch, kv_heads, rows, dim)
    kv_lengths = torch.tensor(lengths, dtype=torch.int32)
    # Every verify row reads the same committed prefix: the prefix-only decode is not causal.
    out, lse = kitchen.flash_attention_decode_gqa(q, cache_k, cache_v, kv_lengths, return_lse=True, causal=False)
    merged = torch.empty_like(out)
    if mask is None:
        kitchen.flash_attention_decode_step_merge(out, lse, q, step_k, step_v, merged)
    else:
        kitchen.flash_attention_decode_tree_merge(out, lse, q, step_k, step_v, torch.tensor(mask, dtype=torch.int32), merged)
    assert merged.shape == (batch, rows, heads * dim) and lse.shape == (batch, heads, rows)
    return merged[..., ::CHANNEL_STEP].contiguous(), lse.contiguous()


def literal(name, tensor):
    bits = struct.unpack(f"<{tensor.numel()}I", tensor.numpy().tobytes())
    lines = [f"    public static readonly uint[] {name} =", "    ["]
    for i in range(0, len(bits), 8):
        lines.append("        " + " ".join(f"0x{b:08X}," for b in bits[i:i + 8]))
    lines.append("    ];")
    lines.append("")
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    source = Path(kitchen.__file__)
    digest = hashlib.sha256(source.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
    lines = [
        "// Generated by benchmarks/attention/kitchen_merge_vectors.py; do not edit by hand.",
        f"// Comfy Kitchen {importlib.metadata.version('comfy_kitchen')}, flash_attention.py sha256 {digest} (line endings normalized),",
        f"// torch {torch.__version__.split('+')[0]} on CPU, F32.",
        "namespace HartsyInference.Core.Tests.Backends;",
        "",
        "/// <summary>Outputs of Comfy Kitchen's torch decode and merge definitions for the cases DecodeMergeReferenceTests",
        "/// rebuilds: per case the merged output <c>[batch, row, heads × headDim]</c>, every ChannelStep-th value of each row,",
        "/// and the prefix log-sum-exp <c>[batch, head, row]</c>, as F32 bits.</summary>",
        "internal static class DecodeMergeKitchenVectors",
        "{",
        f"    public const int ChannelStep = {CHANNEL_STEP};",
        "",
    ]
    count = 0
    for index, (name, *shape) in enumerate(cases()):
        merged, lse = run(*shape, seed=4000 + 100 * index)
        lines += literal(name, merged)
        lines += literal(name + "Lse", lse)
        count += 1
    lines[-1] = "}"
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out}: {count} cases", file=sys.stderr)


if __name__ == "__main__":
    main()
