"""Reference vectors for the Sol-Attn reference test, from Comfy Kitchen's eager definition.

Run with the isolated Kitchen environment (README, "Isolated Kitchen environment"), on CPU:

    python -s benchmarks/attention/kitchen_sol_vectors.py --out tests/HartsyInference.Core.Tests/Backends/SolAttentionKitchenVectors.cs

The Kitchen's eager `sol_attn` defines the algorithm; its GPU kernels are compared with it by cosine only. Each case
below builds its inputs with a generator the C# test repeats bit for bit, runs the eager definition on F32 CPU tensors,
and keeps a sample of the output: SAMPLE_ROWS rows spread over the sequence, every CHANNEL_STEP-th channel. The C# test
recomputes the same cases with SolAttentionReference and compares the sample.
"""
import argparse
import hashlib
import importlib
import importlib.metadata
import struct
import sys
from pathlib import Path

import torch

import comfy_kitchen

HEAD_DIM = 128
SAMPLE_ROWS = 10
CHANNEL_STEP = 8


def uniform(count, seed):
    """count values in [-1, 1) from a 32-bit LCG: exact in F32, and trivially the same in C#."""
    state = seed & 0xFFFFFFFF
    values = []
    for _ in range(count):
        state = (state * 1664525 + 1013904223) & 0xFFFFFFFF
        values.append(((state >> 8) & 0xFFFF) / 32768.0 - 1.0)
    return torch.tensor(values, dtype=torch.float32)


def inputs(batch, tokens, heads, seed):
    """Q, K, V of shape (B, T, H, D). Noise, plus a component shared by every third block so routing has structure."""
    shape = (batch, tokens, heads, HEAD_DIM)
    count = batch * tokens * heads * HEAD_DIM
    q = uniform(count, seed).reshape(shape)
    k = uniform(count, seed + 1).reshape(shape)
    v = uniform(count, seed + 2).reshape(shape)
    basis = uniform(3 * HEAD_DIM, seed + 3).reshape(3, HEAD_DIM)
    block = torch.arange(tokens) // 64
    shared = basis[block % 3] * 2.0
    q = q + shared[None, :, None, :]
    k = k + shared[None, :, None, :]
    return q, k, v


def cases():
    yield "TauRaggedLastBlock", dict(batch=1, tokens=200, heads=2, seed=101), dict(tau=1.0)
    yield "TauLow", dict(batch=1, tokens=320, heads=2, seed=202), dict(tau=0.25)
    yield "TauHighRoutesLittle", dict(batch=1, tokens=384, heads=1, seed=303), dict(tau=3.0)
    yield "TopK", dict(batch=1, tokens=448, heads=2, seed=404), dict(topk_ratio=0.4)
    yield "NoTail", dict(batch=1, tokens=320, heads=2, seed=505), dict(tau=1.0, tail=False)
    yield "Sinks", dict(batch=1, tokens=320, heads=2, seed=606), dict(tau=1.5, sink_blocks=[0, 1], sink_q=[2, 3])
    yield "TopKWithSinks", dict(batch=1, tokens=448, heads=1, seed=707), dict(topk_ratio=0.3, sink_blocks=[1, 3])
    yield "KeyBias", dict(batch=2, tokens=256, heads=2, seed=808), dict(tau=1.0, key_bias="float")
    yield "KeyMask", dict(batch=1, tokens=192, heads=2, seed=909), dict(tau=0.5, key_bias="bool")
    yield "BlockLengths", dict(batch=1, tokens=256, heads=2, seed=1010), dict(tau=1.0, block_len=[64, 40, 1, 64])
    yield "CoarseGate", dict(batch=1, tokens=256, heads=2, seed=1111), dict(topk_ratio=0.5, tail=False, coarse_gate=True)
    yield "CustomScale", dict(batch=2, tokens=200, heads=3, seed=1212), dict(tau=0.75, scale=0.05)


def run(shape, options):
    q, k, v = inputs(**shape)
    batch, tokens = shape["batch"], shape["tokens"]
    kwargs = dict(options)
    if kwargs.get("key_bias") == "float":
        kwargs["key_bias"] = uniform(batch * tokens, shape["seed"] + 4).reshape(batch, tokens) * 2.0
    elif kwargs.get("key_bias") == "bool":
        kwargs["key_bias"] = uniform(tokens, shape["seed"] + 4) > -0.6
    if "block_len" in kwargs:
        kwargs["block_len"] = torch.tensor(kwargs["block_len"], dtype=torch.int32)
    if kwargs.pop("coarse_gate", False):
        kwargs["coarse_gate"] = uniform(q.numel(), shape["seed"] + 5).reshape(q.shape) * 0.5
    out = comfy_kitchen.sol_attn(q, k, v, **kwargs)
    assert out.dtype == torch.float32 and out.shape == q.shape
    rows = [round(i * (tokens - 1) / (SAMPLE_ROWS - 1)) for i in range(SAMPLE_ROWS)]
    sample = out[:, rows][..., ::CHANNEL_STEP].contiguous()
    return rows, sample


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    source = Path(importlib.import_module("comfy_kitchen.backends.eager.sol_attn").__file__)
    digest = hashlib.sha256(source.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
    lines = [
        "// Generated by benchmarks/attention/kitchen_sol_vectors.py; do not edit by hand.",
        f"// Comfy Kitchen {importlib.metadata.version('comfy_kitchen')}, eager sol_attn.py sha256 {digest} (line endings normalized),",
        f"// torch {torch.__version__.split('+')[0]} on CPU, F32.",
        "namespace HartsyInference.Core.Tests.Backends;",
        "",
        "/// <summary>Sampled outputs of Comfy Kitchen's eager Sol-Attn definition for the cases SolAttentionReferenceTests",
        "/// rebuilds: for each case, SampleRows rows spread over the sequence and every ChannelStep-th channel, as F32 bits in",
        "/// <c>[batch, row, head, channel]</c> order.</summary>",
        "internal static class SolAttentionKitchenVectors",
        "{",
        f"    public const int SampleRows = {SAMPLE_ROWS}, ChannelStep = {CHANNEL_STEP};",
        "",
    ]
    for name, shape, options in cases():
        rows, sample = run(shape, options)
        bits = struct.unpack(f"<{sample.numel()}I", sample.numpy().tobytes())
        lines.append(f"    public static readonly int[] {name}Rows = [{', '.join(str(r) for r in rows)}];")
        lines.append(f"    public static readonly uint[] {name} =")
        lines.append("    [")
        for i in range(0, len(bits), 8):
            lines.append("        " + " ".join(f"0x{b:08X}," for b in bits[i:i + 8]))
        lines.append("    ];")
        lines.append("")
    lines[-1] = "}"
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out}: {sum(1 for _ in cases())} cases", file=sys.stderr)


if __name__ == "__main__":
    main()
